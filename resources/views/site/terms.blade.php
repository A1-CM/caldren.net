        <div class="policy-intro"><span class="eyebrow">THE DETAILS</span><h2>Use energy forecasts with context.</h2><p>These terms describe Caldren’s current AI-assisted energy forecasting and optimization insights for commercial energy teams.</p></div>
        <article class="policy-card">
            <section id="terms-service" class="policy-section">
                <span class="policy-section-number">01 / SERVICE</span>
                <h2>The service</h2>
                <p>Caldren helps teams organize site-level energy readings and utility bills, review historical trends, and request AI-assisted seven-day energy and peak estimates when sufficient interval data is available. It highlights possible peak and tariff opportunities for your team to assess as part of energy optimization decisions.</p>
            </section>
            <section id="terms-accounts" class="policy-section">
                <span class="policy-section-number">02 / WORKSPACES</span>
                <h2>Accounts and teams</h2>
                <p>You are responsible for keeping your account credentials secure and for the people you invite to your organization. Team members with access to a workspace can see that organization's site-level energy information. Workspace owners manage invitations and can use demo checkout.</p>
            </section>
            <section id="terms-data" class="policy-section">
                <span class="policy-section-number">03 / INPUTS</span>
                <h2>Data you provide</h2>
                <p>Upload or enter only information you are authorized to use. Check the accuracy of readings, bills, site details, and tariff settings before relying on an analysis. Keep personal and sensitive information out of building names, CSV files, and contact messages.</p>
            </section>
            <section id="terms-estimates" class="policy-section">
                <span class="policy-section-number">04 / ANALYSIS</span>
                <h2>Estimates and decisions</h2>
                <p>Forecasts, peak alerts, and opportunities are estimates based on the information available to Caldren. They do not guarantee accuracy, savings, or a particular operating result. Review them against actual conditions and use your own judgment before making energy or operational decisions. Caldren does not control equipment.</p>
            </section>
            <section id="terms-trial" class="policy-section">
                <span class="policy-section-number">05 / ACCESS</span>
                <h2>Trial and access</h2>
                <p>New organizations receive a 30-day trial without providing a card, with a maximum of 3 buildings in the Site trial workspace. After access expires, historical workspace data remains visible, while adding buildings or bills, uploading readings, and generating forecasts are gated until access is active again.</p>
            </section>
            <section id="terms-demo" class="policy-section">
                <span class="policy-section-number">06 / DEMO BILLING</span>
                <h2>Demo checkout</h2>
                <p>Caldren offers Site at USD 49/month for up to 3 buildings and Portfolio at USD 99/month for up to 10. Campus portfolios can contact sales for a tailored discussion. The current checkout is a clearly labelled simulation available to signed-in workspace owners. It accepts only the displayed 4242 demo number. A successful simulation records the selected tier and payment amount and adds one month of access; no money is charged, no card details are stored, and access does not renew automatically.</p>
            </section>
            <section id="terms-availability" class="policy-section">
                <span class="policy-section-number">07 / AVAILABILITY</span>
                <h2>Availability and retries</h2>
                <p>Forecast generation depends on an external API and can fail or be unavailable. If it fails, historical data remains available in the workspace and you can try again later. For questions about the service, contact <a href="mailto:{{ config('mail.contact_to') }}">{{ config('mail.contact_to') }}</a>.</p>
            </section>
